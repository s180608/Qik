CREATE TABLE shop_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id BIGINT REFERENCES users(id), rider_id BIGINT REFERENCES users(id),
 request_key VARCHAR(255) NOT NULL, address VARCHAR(255) NOT NULL, postcode VARCHAR(255) NOT NULL,
 status VARCHAR(255), subtotal NUMERIC(10,2),delivery_fee NUMERIC(10,2),total NUMERIC(10,2),
 created_at TIMESTAMP WITH TIME ZONE,updated_at TIMESTAMP WITH TIME ZONE,simulated BOOLEAN NOT NULL,version BIGINT,
 UNIQUE(customer_id,request_key)
);
CREATE TABLE order_items (order_id BIGINT NOT NULL REFERENCES shop_orders(id),product_id BIGINT,name VARCHAR(255),quantity INTEGER NOT NULL,unit_price NUMERIC(10,2));
CREATE INDEX orders_customer ON shop_orders(customer_id);
CREATE INDEX orders_rider ON shop_orders(rider_id);
