CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, first_name VARCHAR(255) NOT NULL,
 last_name VARCHAR(255) NOT NULL, email VARCHAR(255) NOT NULL UNIQUE, password VARCHAR(255) NOT NULL,
 phone_number VARCHAR(255), role VARCHAR(255) NOT NULL, active BOOLEAN NOT NULL,
 created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP
);
CREATE TABLE categories (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name VARCHAR(255) NOT NULL UNIQUE,description VARCHAR(255),image_url VARCHAR(255),active BOOLEAN,created_at TIMESTAMP);
CREATE TABLE products (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name VARCHAR(255) NOT NULL,description VARCHAR(255),price NUMERIC(10,2) NOT NULL,image_url VARCHAR(255),stock_quantity INTEGER NOT NULL CHECK(stock_quantity >= 0),category_id BIGINT NOT NULL REFERENCES categories(id),active BOOLEAN,created_at TIMESTAMP);
